#!/usr/bin/env bun
// Writes `Casks/obol.rb`, the Homebrew cask of the macOS builds, from a release's `manifest.json`.
// The tap is this repository itself:
//
//   brew tap <owner>/<repo> https://github.com/<owner>/<repo>
//   brew install --cask obol
//
// Usage:
//   bun scripts/brew-cask.ts <manifest.json> [--repo=owner/name] [--out=Casks/obol.rb]
//
// `release.yml` runs it after publishing, so the cask always names the latest release with the
// sha256 the manifest carries for each macOS zip — Apple silicon and Intel each get their
// Electrobun build, with the same zip name. A manifest older than the cask on disk is refused
// with exit 0 and nothing written: re-running the release of an old version never moves the cask
// backwards.
//
// The builds are signed ad hoc (no Apple Developer certificate in CI), so Gatekeeper blocks a
// quarantined copy; the cask clears the flag in a postflight step and macOS keeps a copy in the
// cask room instead of translocating the app.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

export const CASK_PATH = 'Casks/obol.rb';
const SHA256 = /^[0-9a-f]{64}$/;
const REPO_PATTERN = /^[\w.-]+\/[\w.-]+$/;

export interface CaskInput {
  version: string;
  repo: string;
  arm64Sha: string;
  x86Sha: string;
}

export const APP_BUNDLE = 'Obol.app';
/** The bundle id and the data directory are the `copland.obol` identity of every Obol install. */
export const BUNDLE_ID = 'copland.obol';
const APP_TITLE = 'Obol';
const APP_DESC = 'Personal finance ledger: earned, spent, sound';

/** What the cask needs out of a merged `manifest.json`, or the reason it cannot be read. */
export function caskInputFrom(manifest: unknown, repo: string): CaskInput | string {
  if (typeof manifest !== 'object' || manifest === null) return 'the manifest is not an object';
  const fields = manifest as Record<string, unknown>;
  const version = 'version' in fields ? fields.version : undefined;
  const mac = 'mac' in fields ? fields.mac : undefined;
  if (typeof version !== 'string' || version.trim() === '') return 'the manifest has no version';
  if (typeof mac !== 'object' || mac === null) return 'the manifest has no mac block';
  const sha = (entry: unknown): string | null => {
    if (typeof entry !== 'object' || entry === null) return null;
    const value = (entry as Record<string, unknown>).sha256;
    return typeof value === 'string' && SHA256.test(value) ? value : null;
  };
  const macField = mac as Record<string, unknown>;
  const arm64Sha = sha('arm64' in macField ? macField.arm64 : undefined);
  const x86Sha = sha('x86_64' in macField ? macField.x86_64 : undefined);
  if (arm64Sha === null || x86Sha === null) {
    return 'the manifest lacks a sha256 for mac.arm64 or mac.x86_64';
  }
  if (!REPO_PATTERN.test(repo)) return `not an owner/name repository: ${repo}`;
  return { version: version.trim(), repo, arm64Sha, x86Sha };
}

/** The version the cask on disk names, or null without one. */
export function caskVersion(source: string): string | null {
  const match = /\bversion\s+"([^"]+)"/.exec(source);
  return match === null ? null : match[1];
}

export function caskSource(input: CaskInput): string {
  return `# Generated by desktop/scripts/brew-cask.ts from the release manifest; do not edit by hand.
cask "obol" do
  arch arm: "arm64", intel: "x86_64"

  version "${input.version}"
  sha256 arm:   "${input.arm64Sha}",
         intel: "${input.x86Sha}"

  url "https://github.com/${input.repo}/releases/download/release-#{version}/obol-#{version}-macos-#{arch}.zip"
  name "${APP_TITLE}"
  desc "${APP_DESC}"
  homepage "https://github.com/${input.repo}"

  # brew audit requires the bundle's own LSMinimumSystemVersion here; Obol's floor is what the
  # Electrobun bundle declares (macOS 14+ on the Apple silicon zip).
  depends_on macos: :sonoma

  app "${APP_BUNDLE}"

  # The builds are signed ad hoc, so Gatekeeper blocks a quarantined copy. This is the release
  # step that clears the flag; writable_paths also keeps macOS from translocating the app.
  postflight_steps do
    run "/usr/bin/xattr",
        args:           ["-dr", "com.apple.quarantine", "{{appdir}}/${APP_BUNDLE}"],
        writable_paths: ["${APP_BUNDLE}"],
        writable_base:  :appdir
  end

  zap trash: [
    "~/Library/Application Support/${BUNDLE_ID}",
    "~/Library/Caches/${BUNDLE_ID}",
    "~/Library/HTTPStorages/${BUNDLE_ID}.binarycookies",
    "~/Library/Preferences/${BUNDLE_ID}.plist",
    "~/Library/WebKit/${BUNDLE_ID}",
  ]
end
`;
}

/**
 * Semver 2.0.0 §11 on purpose narrow: three numeric components, optional hotfix letters on the
 * patch (`0.5.5a`, the release forms the workflows gate on) and an optional pre-release; build
 * metadata is ignored, as §10 says. `null`/`''` inputs compare as `0` (the safe answer: never
 * refuse, never regress past what cannot be read).
 */
const NUMERIC_IDENTIFIER = /^[0-9]+$/;
const IDENTIFIER = /^[0-9A-Za-z-]+$/;
/** The patch with its hotfix letters: `5`, `5a`, `5b`. Only the third number carries letters. */
const PATCH_WITH_HOTFIX = /^([0-9]+)([a-z]*)$/;

interface ParsedVersion {
  numbers: readonly number[];
  hotfix: string;
  /** Empty when there is no pre-release, which is what makes `1.0.0` newer than `1.0.0-rc`. */
  prerelease: readonly string[];
}

function parseVersion(text: string): ParsedVersion | null {
  const trimmed = text.trim().replace(/^v/i, '');
  const withoutBuild = trimmed.split('+')[0] ?? '';
  const dash = withoutBuild.indexOf('-');
  const core = dash === -1 ? withoutBuild : withoutBuild.slice(0, dash);
  const pre = dash === -1 ? '' : withoutBuild.slice(dash + 1);
  if (core === '') return null;

  const parts = core.split('.');
  if (parts.length > 3) return null;
  const numbers: number[] = [];
  let hotfix = '';
  for (const [index, part] of parts.entries()) {
    const patch = index === 2 ? PATCH_WITH_HOTFIX.exec(part) : null;
    if (patch !== null) {
      numbers.push(Number.parseInt(patch[1] ?? '', 10));
      hotfix = patch[2] ?? '';
      continue;
    }
    if (!NUMERIC_IDENTIFIER.test(part)) return null;
    numbers.push(Number.parseInt(part, 10));
  }
  while (numbers.length < 3) numbers.push(0);

  const prerelease = pre === '' ? [] : pre.split('.');
  for (const identifier of prerelease) {
    if (!IDENTIFIER.test(identifier)) return null;
  }
  return { numbers, hotfix, prerelease };
}

export function compareVersions(left: string, right: string): number {
  const a = parseVersion(left);
  const b = parseVersion(right);
  if (a === null || b === null) return 0;

  for (let index = 0; index < 3; index += 1) {
    const difference = (a.numbers[index] ?? 0) - (b.numbers[index] ?? 0);
    if (difference !== 0) return difference < 0 ? -1 : 1;
  }

  // `0.5.5` < `0.5.5a` < `0.5.5b` < `0.5.6`: a longer run of hotfix letters is newer, `z` < `aa`.
  if (a.hotfix !== b.hotfix) {
    if (a.hotfix.length !== b.hotfix.length) return a.hotfix.length < b.hotfix.length ? -1 : 1;
    return a.hotfix < b.hotfix ? -1 : 1;
  }

  if (a.prerelease.length === 0 && b.prerelease.length === 0) return 0;
  if (a.prerelease.length === 0) return 1;
  if (b.prerelease.length === 0) return -1;

  const length = Math.max(a.prerelease.length, b.prerelease.length);
  for (let index = 0; index < length; index += 1) {
    const one = a.prerelease[index];
    const other = b.prerelease[index];
    if (one === undefined) return -1;
    if (other === undefined) return 1;
    const oneNumeric = NUMERIC_IDENTIFIER.test(one);
    const otherNumeric = NUMERIC_IDENTIFIER.test(other);
    if (oneNumeric && otherNumeric) {
      const difference = Number(one) - Number(other);
      if (difference !== 0) return difference < 0 ? -1 : 1;
      continue;
    }
    if (oneNumeric) return -1;
    if (otherNumeric) return 1;
    if (one !== other) return one < other ? -1 : 1;
  }
  return 0;
}

function main(argv: string[]): number {
  const manifestPath = argv.find((value) => !value.startsWith('--'));
  const flag = (name: string): string | undefined => {
    const inline = argv.find((value) => value.startsWith(`--${name}=`));
    if (inline === undefined) return undefined;
    const value = inline.slice(`--${name}=`.length);
    return value === '' ? undefined : value;
  };
  if (manifestPath === undefined) {
    console.error('usage: bun scripts/brew-cask.ts <manifest.json> [--repo=owner/name] [--out=Casks/obol.rb]');
    return 2;
  }
  const out = flag('out') ?? CASK_PATH;
  // In the release job this comes from --repo; a bare local run falls back to the checkout's own
  // remote (GITHUB_REPOSITORY in Actions, otherwise `git remote get-url origin`).
  let repo = flag('repo');
  if (repo === undefined) {
    const result = Bun.spawnSync(['git', 'remote', 'get-url', 'origin'], {
      stdout: 'pipe',
      stderr: 'ignore',
    });
    if (result.exitCode === 0) {
      const url = result.stdout.toString().trim().replace(/\.git$/, '');
      const remote = /(?:[:/])([\w.-]+)\/([\w.-]+)$/.exec(url.replace(/@/, '/').replace(/^git@/, ''));
      repo = remote === null ? undefined : `${remote[1]}/${remote[2]}`;
    }
  }
  repo ??= process.env.GITHUB_REPOSITORY;
  if (repo === undefined || !REPO_PATTERN.test(repo)) {
    console.error(`brew-cask: no owner/name repository given or derivable (pass --repo=owner/name)`);
    return 2;
  }
  let input: unknown;
  try {
    input = JSON.parse(readFileSync(manifestPath, 'utf8'));
  } catch {
    console.error(`brew-cask: ${manifestPath} is not readable JSON`);
    return 1;
  }
  const parsed = caskInputFrom(input, repo);
  if (typeof parsed === 'string') {
    console.error(`brew-cask: ${parsed}`);
    return 1;
  }
  const current = existsSync(out) ? caskVersion(readFileSync(out, 'utf8')) : null;
  if (current !== null && compareVersions(parsed.version, current) < 0) {
    console.log(`brew-cask: ${out} already names ${current}, newer than ${parsed.version}; left as is`);
    return 0;
  }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, caskSource(parsed));
  console.log(`brew-cask: ${out} → ${parsed.version} (${parsed.repo})`);
  return 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
